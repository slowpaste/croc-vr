'use strict';
const fs=require('node:fs'),path=require('node:path'),os=require('node:os'),crypto=require('node:crypto'),assert=require('node:assert/strict');
const {prepare}=require('./prepare-cutscene-deployment.cjs');
const root=fs.mkdtempSync(path.join(os.tmpdir(),'croc-deployment-test-'));
try{
 const content=path.join(root,'content');fs.mkdirSync(content);
 function write(file,value){const target=path.join(content,file);fs.mkdirSync(path.dirname(target),{recursive:true});fs.writeFileSync(target,typeof value==='string'?value:JSON.stringify(value));}
 write('resources/empty.json',{files:[],frames:[]});write('resources/tables.json',{});
 write('resources/room.strategy.json',{commands:[177]});write('audio/gameplay.wav','sound');
 write('textures/intro.json',{animationPatches:[{image:'textures/spin.png'}]});write('textures/spin.png','animation');write('textures/intro.png','pixels');write('textures/intro-mask.png','mask');
 write('resources/stage.res','mesh');write('resources/sequence-cache.json',{scene_id:0,fingerprint:'test',parts:[{frames:[{passes:[{kind:'opaque',meshes:{actor:{file:'resources/stage.res',sha256:'test'}}}]}]}]});
 const local={sourceSha256:'source',runtimeTables:'resources/tables.json'};
 write('music/xa-01.wav','waveform');write('music/xa-01.sectors','original sectors');
 const music={streams:[{file:'music/xa-01.wav',compressedFile:'music/xa-01.sectors',sourceSha256:crypto.createHash('sha256').update('original sectors').digest('hex')}]};
 write('music/index.json',music);local.musicIndex='music/index.json';
 write('options/font.json',{font:'original'});write('options/icon.json',{icon:'Croc'});
 local.optionsFont={file:'options/font.json'};local.saveIcon={file:'options/icon.json'};
 write('models/player.json',{model:'Croc'});local.character={animations:{idle:'resources/room.strategy.json'},file:'models/player.json'};
 for(const key of ['cutscenePoses','cutsceneMeshes','cutsceneBackgroundMeshes','cutsceneAudio','cutsceneCompositor','models','maps','cutsceneRooms','cutsceneSequences','cutsceneSequenceAudio','credits'])local[key]=[{file:'resources/empty.json'}];
 local.textures=[{name:'INTRO.BIN',file:'textures/intro.json',image:'textures/intro.png',maskImage:'textures/intro-mask.png'}];
 local.cutsceneSequenceCaches=[{scene_id:0,fingerprint:'test',file:'resources/sequence-cache.json'}];local.creditsFonts={file:'resources/empty.json'};
 write('manifest.json',local);const base=path.join(root,'base.json');fs.writeFileSync(base,JSON.stringify({sourceSha256:'source',textures:[]}));
 const out=path.join(root,'staged'),report=prepare(content,base,out);
 assert.equal(fs.readFileSync(path.join(out,'resources/stage.res'),'utf8'),'mesh');
 assert.equal(fs.readFileSync(path.join(out,'resources/room.strategy.json'),'utf8'),'{"commands":[177]}');
 assert.equal(fs.readFileSync(path.join(out,'audio/gameplay.wav'),'utf8'),'sound');
 assert.deepEqual(JSON.parse(fs.readFileSync(path.join(out,'music/index.json'))),music);
 assert.equal(fs.readFileSync(path.join(out,'music/xa-01.sectors'),'utf8'),'original sectors');
 assert.equal(fs.readFileSync(path.join(out,'music/xa-01.wav'),'utf8'),'waveform');
 assert.equal(fs.readFileSync(path.join(out,'options/font.json'),'utf8'),'{"font":"original"}');
 assert.equal(fs.readFileSync(path.join(out,'options/icon.json'),'utf8'),'{"icon":"Croc"}');
 assert.equal(fs.readFileSync(path.join(out,'textures/spin.png'),'utf8'),'animation');
 assert.equal(JSON.parse(fs.readFileSync(path.join(out,'manifest.json'))).cutsceneSequences.length,1);
 assert.deepEqual(JSON.parse(fs.readFileSync(path.join(out,'manifest.json'))).character,local.character);
 assert.equal(fs.readFileSync(path.join(out,'models/player.json'),'utf8'),'{"model":"Croc"}');
 const expected=fs.readFileSync(path.join(out,'sha256.txt'),'utf8').trim().split('\n').reduce((sum,line)=>sum+fs.statSync(path.join(out,line.slice(66))).size,0);
 assert.equal(report.bytes,expected);
 write('music/xa-01.sectors','corrupt sectors');
 assert.throws(()=>prepare(content,base,path.join(root,'bad-music')),/music payload.*hash differs/);
 assert.equal(fs.existsSync(path.join(root,'bad-music')),false);
 write('music/xa-01.sectors','original sectors');
 local.bootstrapMusic={file:'resources/missing-bootstrap.json'};write('manifest.json',local);
 assert.throws(()=>prepare(content,base,path.join(root,'missing')),/ENOENT/);
 assert.equal(fs.existsSync(path.join(root,'missing')),false);
 delete local.bootstrapMusic;
 local.cutsceneSequenceCaches[0].fingerprint='wrong';write('manifest.json',local);
 assert.throws(()=>prepare(content,base,path.join(root,'bad')),/identity differs/);
 assert.equal(fs.existsSync(path.join(root,'bad')),false);
 console.log('PASS: deployment staging includes multipart cache meshes, credits, masks, correct byte totals and rejects mismatched cache identity before writing');
}finally{assert(path.resolve(root).startsWith(path.resolve(os.tmpdir())+path.sep+'croc-deployment-test-'));fs.rmSync(root,{recursive:true,force:true});}
